from __future__ import annotations

import argparse
import json
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Validate a prepared KITTI raw benchmark workspace before running cuVSLAM / FAST-LIVO2."
    )
    parser.add_argument("--workspace", required=True, help="Workspace generated by prepare_kitti_raw_benchmark.py")
    return parser.parse_args()


def count_lines(path: Path) -> int:
    return sum(1 for line in path.open("r", encoding="utf-8") if line.strip())


def validate_dir(path: Path, expected_name: str, errors: list[str]) -> None:
    if not path.exists():
        errors.append(f"Missing {expected_name}: {path}")
        return


def main() -> None:
    args = parse_args()
    workspace = Path(args.workspace).expanduser().resolve()
    summary_path = workspace / "summary.json"
    if not summary_path.exists():
        raise SystemExit(f"Missing workspace summary: {summary_path}")
    summary = json.loads(summary_path.read_text(encoding="utf-8"))

    errors: list[str] = []
    warnings: list[str] = []

    selected = int(summary["frame_count_selected"])
    cu_dir = Path(summary["cuvslam_sequence_dir"])
    fl_dir = Path(summary["fastlivo2_sequence_dir"])
    gt_rel = Path(summary["gt_relative_tum"])
    gt_abs = Path(summary["gt_absolute_tum"])

    validate_dir(cu_dir / "image_0", "cuVSLAM image_0", errors)
    validate_dir(cu_dir / "image_1", "cuVSLAM image_1", errors)
    validate_dir(fl_dir / "image_00", "FAST-LIVO2 image_00", errors)
    validate_dir(fl_dir / "image_01", "FAST-LIVO2 image_01", errors)
    validate_dir(fl_dir / "velodyne_points", "FAST-LIVO2 velodyne_points", errors)
    validate_dir(fl_dir / "oxts_data", "FAST-LIVO2 oxts_data", errors)

    times_count = count_lines(cu_dir / "times.txt") if (cu_dir / "times.txt").exists() else -1
    abs_times_count = count_lines(cu_dir / "timestamps_abs.txt") if (cu_dir / "timestamps_abs.txt").exists() else -1
    frame_ids_count = count_lines(cu_dir / "frame_ids.txt") if (cu_dir / "frame_ids.txt").exists() else -1
    gt_rel_count = count_lines(gt_rel) if gt_rel.exists() else -1
    gt_abs_count = count_lines(gt_abs) if gt_abs.exists() else -1
    velo_ts_count = count_lines(fl_dir / "velodyne_timestamps.txt") if (fl_dir / "velodyne_timestamps.txt").exists() else -1
    oxts_ts_count = count_lines(fl_dir / "oxts_timestamps.txt") if (fl_dir / "oxts_timestamps.txt").exists() else -1

    for label, count in [
        ("times.txt", times_count),
        ("timestamps_abs.txt", abs_times_count),
        ("frame_ids.txt", frame_ids_count),
        ("gt_tum_relative.txt", gt_rel_count),
        ("gt_tum_absolute.txt", gt_abs_count),
        ("velodyne_timestamps.txt", velo_ts_count),
        ("oxts_timestamps.txt", oxts_ts_count),
    ]:
        if count != selected:
            errors.append(f"{label} line count mismatch: expected {selected}, got {count}")

    image_0_count = len(list((cu_dir / "image_0").glob("*.png"))) if (cu_dir / "image_0").exists() else -1
    image_1_count = len(list((cu_dir / "image_1").glob("*.png"))) if (cu_dir / "image_1").exists() else -1
    if image_0_count != selected:
        errors.append(f"cuVSLAM image_0 count mismatch: expected {selected}, got {image_0_count}")
    if image_1_count != selected:
        errors.append(f"cuVSLAM image_1 count mismatch: expected {selected}, got {image_1_count}")
    if not (cu_dir / "image_0" / "000000.png").exists():
        errors.append("cuVSLAM image_0/000000.png is missing")
    if not (cu_dir / "image_1" / "000000.png").exists():
        errors.append("cuVSLAM image_1/000000.png is missing")

    if gt_rel.exists() and gt_abs.exists():
        first_rel = gt_rel.read_text(encoding="utf-8").splitlines()[0].split()[0]
        first_abs = gt_abs.read_text(encoding="utf-8").splitlines()[0].split()[0]
        if abs(float(first_rel)) > 1e-6:
            warnings.append(f"Relative GT does not start at 0: first timestamp={first_rel}")
        if float(first_abs) < 1e9:
            warnings.append(f"Absolute GT timestamp looks too small: first timestamp={first_abs}")

    report = {
        "workspace": str(workspace),
        "frame_count_selected": selected,
        "status": "ok" if not errors else "error",
        "errors": errors,
        "warnings": warnings,
        "counts": {
            "times": times_count,
            "timestamps_abs": abs_times_count,
            "frame_ids": frame_ids_count,
            "cuvslam_image_0": image_0_count,
            "cuvslam_image_1": image_1_count,
            "gt_relative": gt_rel_count,
            "gt_absolute": gt_abs_count,
            "velodyne_timestamps": velo_ts_count,
            "oxts_timestamps": oxts_ts_count,
        },
    }
    out = workspace / "validation_report.json"
    out.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(report, indent=2, ensure_ascii=False))
    if errors:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
